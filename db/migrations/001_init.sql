-- Wavy v2 — skema awal (2 role: admin & customer). Satu-satunya sumber skema:
-- dipakai scripts/migrate.ts, scripts/db-reset.ts, dan tests/preload.ts.
-- Aturan: file migration yang sudah di-merge tidak pernah diedit; perubahan = file baru 002_..., 003_...
-- Nama kolom yang dikirim ke klien (date, is_scanned, read, wa_consent) sengaja sama dengan skema lama.

-- ---------------------------------------------------------------------------
-- Akun
-- ---------------------------------------------------------------------------
CREATE TABLE admins (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL CHECK (btrim(name) <> ''),
  email       text NOT NULL UNIQUE CHECK (position('@' IN email) > 1),
  password    text NOT NULL,                       -- hash bcrypt (cost 10), lihat scripts/create-admin.ts
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE customers (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       text NOT NULL UNIQUE CHECK (position('@' IN email) > 1),
  name        text CHECK (name IS NULL OR char_length(name) <= 80), -- NULL = akun baru, isi nama setelah OTP
  phone       text NOT NULL DEFAULT '' CHECK (char_length(phone) <= 30),
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- OTP login customer (email -> kode 6 digit, berlaku 5 menit).
-- expires_at sengaja timestamp tanpa zona: dibandingkan dengan LOCALTIMESTAMP di auth.service.
CREATE TABLE otp_codes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       text NOT NULL,
  code        text NOT NULL CHECK (code ~ '^[0-9]{6}$'),
  expires_at  timestamp NOT NULL,
  used        boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_otp_codes_email_code ON otp_codes (email, code);

-- ---------------------------------------------------------------------------
-- Katalog (milik platform, dikelola admin)
-- ---------------------------------------------------------------------------
CREATE TABLE artists (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL CHECK (btrim(name) <> ''),
  genre       text NOT NULL DEFAULT '',
  photo_url   text NOT NULL DEFAULT '',
  bio         text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE events (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artist_id         bigint NOT NULL REFERENCES artists (id) ON DELETE RESTRICT,
  created_by        bigint REFERENCES admins (id) ON DELETE SET NULL,
  title             text NOT NULL CHECK (btrim(title) <> ''),
  category          text NOT NULL DEFAULT '',
  venue             text NOT NULL DEFAULT '',     -- teks biasa (fitur venue/section ditunda)
  date              timestamptz NOT NULL,
  poster_url        text NOT NULL DEFAULT '',
  banner_url        text NOT NULL DEFAULT '',
  description       text NOT NULL DEFAULT '',
  terms_conditions  text NOT NULL DEFAULT '',
  gallery           text NOT NULL DEFAULT '[]',   -- JSON array URL gambar
  seatmap           text NOT NULL DEFAULT '',     -- JSON { name, images[] } atau kosong
  status            text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'closed')),
  sales_start_at    timestamptz,                  -- NULL = tanpa batas awal
  sales_end_at      timestamptz,                  -- NULL = tanpa batas akhir
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  -- PRD §4.1: jendela penjualan (juga divalidasi Zod + backoffice.service)
  CONSTRAINT events_sales_window_check CHECK (sales_start_at IS NULL OR sales_end_at IS NULL OR sales_end_at > sales_start_at),
  CONSTRAINT events_sales_end_before_event CHECK (sales_end_at IS NULL OR sales_end_at <= date),
  CONSTRAINT events_sales_start_before_event CHECK (sales_start_at IS NULL OR sales_start_at < date)
);
CREATE INDEX idx_events_artist ON events (artist_id);
CREATE INDEX idx_events_status_date ON events (status, date);

CREATE TABLE ticket_categories (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id    bigint NOT NULL REFERENCES events (id) ON DELETE CASCADE,
  name        text NOT NULL CHECK (btrim(name) <> ''),
  price       numeric(14, 2) NOT NULL CHECK (price >= 0),
  quota       integer NOT NULL CHECK (quota > 0),
  sold        integer NOT NULL DEFAULT 0 CHECK (sold >= 0), -- tiket paid; dipelihara markOrderPaid & refund
  benefits    text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ticket_categories_event_name_key UNIQUE (event_id, name),
  -- target FK komposit orders(ticket_category_id, event_id)
  CONSTRAINT ticket_categories_id_event_key UNIQUE (id, event_id)
);

-- ---------------------------------------------------------------------------
-- Transaksi
-- ---------------------------------------------------------------------------
CREATE TABLE orders (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id         bigint NOT NULL REFERENCES customers (id) ON DELETE RESTRICT,
  event_id            bigint NOT NULL REFERENCES events (id) ON DELETE RESTRICT,
  ticket_category_id  bigint NOT NULL,
  quantity            integer NOT NULL CHECK (quantity BETWEEN 1 AND 4),
  total_price         numeric(14, 2) NOT NULL CHECK (total_price >= 0),
  status              text NOT NULL DEFAULT 'pending_payment'
                      CHECK (status IN ('pending_payment', 'paid', 'expired', 'rejected', 'refunded', 'cancelled')),
  expires_at          timestamptz,                -- pending_payment + 15 menit (lazy expiry, PRD §4.4)
  created_at          timestamptz NOT NULL DEFAULT now(),
  paid_at             timestamptz,
  payment_ref         text,                       -- order_id Midtrans percobaan terakhir
  payment_type        text,
  verified_by         bigint REFERENCES admins (id) ON DELETE SET NULL, -- admin yang approve/reject manual
  -- data pemesan (checkout)
  full_name           text NOT NULL DEFAULT '',
  email               text NOT NULL DEFAULT '',
  phone               text NOT NULL DEFAULT '',
  id_number           text NOT NULL DEFAULT '',
  birth_date          date,
  gender              text NOT NULL DEFAULT '' CHECK (gender IN ('', 'L', 'P')),
  wa_consent          text NOT NULL DEFAULT '' CHECK (wa_consent IN ('', 'Ya', 'Tidak')),
  -- kategori tiket wajib milik event yang sama
  CONSTRAINT orders_category_event_fkey FOREIGN KEY (ticket_category_id, event_id)
    REFERENCES ticket_categories (id, event_id) ON DELETE RESTRICT,
  CONSTRAINT orders_pending_has_expiry CHECK (status <> 'pending_payment' OR expires_at IS NOT NULL),
  CONSTRAINT orders_paid_has_paid_at CHECK (status <> 'paid' OR paid_at IS NOT NULL)
);
CREATE INDEX idx_orders_category_status ON orders (ticket_category_id, status); -- hitung kuota pending
CREATE INDEX idx_orders_customer ON orders (customer_id);
CREATE INDEX idx_orders_event ON orders (event_id);
CREATE INDEX idx_orders_payment_ref ON orders (payment_ref);
CREATE INDEX idx_orders_paid_at ON orders (paid_at) WHERE status = 'paid';

CREATE TABLE tickets (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    bigint NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  owner_id    bigint NOT NULL REFERENCES customers (id) ON DELETE RESTRICT, -- berubah saat transfer
  qr_code     text NOT NULL UNIQUE,               -- JWT bertanda tangan (ticket.service signTicket)
  is_scanned  boolean NOT NULL DEFAULT false,
  scanned_at  timestamptz,
  scanned_by  bigint REFERENCES admins (id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_tickets_order ON tickets (order_id);
CREATE INDEX idx_tickets_owner ON tickets (owner_id);

-- ---------------------------------------------------------------------------
-- Interaksi customer
-- ---------------------------------------------------------------------------
CREATE TABLE reviews (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  bigint NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
  event_id     bigint NOT NULL REFERENCES events (id) ON DELETE CASCADE,
  rating       integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment      text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT reviews_customer_event_key UNIQUE (customer_id, event_id)
);

CREATE TABLE favorite_artists (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  bigint NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
  artist_id    bigint NOT NULL REFERENCES artists (id) ON DELETE CASCADE,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT favorite_artists_customer_artist_key UNIQUE (customer_id, artist_id)
);

-- "Ingatkan saya" saat penjualan dibuka
CREATE TABLE notify_requests (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  bigint NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
  event_id     bigint NOT NULL REFERENCES events (id) ON DELETE CASCADE,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT notify_requests_customer_event_key UNIQUE (customer_id, event_id)
);

CREATE TABLE notifications (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  bigint NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
  title        text NOT NULL,
  message      text NOT NULL,
  read         boolean NOT NULL DEFAULT false,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_notifications_customer ON notifications (customer_id, created_at DESC);
